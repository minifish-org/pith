// OAuthSuccessHTML renders the browser success page.
//
// Ports `oauthSuccessHtml` from packages/ai/src/auth/oauth/oauth-page.ts.
func OAuthSuccessHTML(message string) string {
	return renderPage("Authentication successful", "Authentication successful", message, nil)
}

// OAuthErrorHTML renders the browser error page with an optional details block.
//
// Ports `oauthErrorHtml` from packages/ai/src/auth/oauth/oauth-page.ts.
func OAuthErrorHTML(message string, details *string) string {
	return renderPage("Authentication failed", "Authentication failed", message, details)
}
